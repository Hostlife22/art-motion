export function performanceAt(index: number, phase: number) {
  const keys = roots[index],
    t = clamp(phase);
  let i = 0;
  while (i < keys.length - 2 && t > keys[i + 1][0]) i++;
  const a = keys[i],
    b = keys[i + 1],
    p = smooth((t - a[0]) / (b[0] - a[0]));
  let performedPose = poseAt(choreography[index], t);
  if (index === 17)
    performedPose = {
      ...performedPose,
      hipY: mix(
        performedPose.hipY,
        100,
        1 - smooth(((performedPose.shoulderY ?? 47) - 47) / 27),
      ),
    };
  if (index === 9 && t > 0.19 && t < 0.57) {
    const plank = pushUpAt((t - 0.27) / 0.28);
    const weight =
      t < 0.24
        ? smooth((t - 0.19) / 0.05)
        : t > 0.5
          ? 1 - smooth((t - 0.5) / 0.07)
          : 1;
    performedPose = blend(performedPose, plank, weight);
  }
  return {
    x: mix(a[1], b[1], p),
    y: mix(a[2], b[2], p),
    scale: mix(a[3], b[3], p),
    pose: performedPose,
  };
}
